// Generates src/core/include/anvil/core/language_comments_table.hpp: the comment tokens of the
// languages of VS Code's built-in extensions, read from the `comments` of the language
// configuration that each `contributes.languages` entry names, in the order VS Code registers the
// languages. A configuration that sets a kind of token for a language that an earlier one already
// gave tokens replaces that kind, as `core::LanguageComments::overlaid_with` does.
//   node scripts/generate-language-comments.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { builtinLanguageContributions, vscodeVersion } from './builtin-languages.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const vscodeDir = path.join(root, '.deps', 'vscode');
const output = path.join(root, 'src/core/include/anvil/core/language_comments_table.hpp');

// The parser of the editor's own language configuration reader, with its default options.
const { parse } = await import(path.join(vscodeDir, 'out/vs/base/common/json.js'));

const version = vscodeVersion(vscodeDir);

function quote(text) {
    if (/[\u0000-\u001f\u007f]/.test(text)) {
        throw new Error(`a control character in ${JSON.stringify(text)}`);
    }
    return `"${text.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
}

const isToken = (value) => typeof value === 'string' && value.length > 0;

// The same rules as `core::read_language_comments`: an empty token is no token, and each kind is
// checked on its own.
function readComments(file, languageId) {
    const errors = [];
    const configuration = parse(fs.readFileSync(file, 'utf8'), errors);
    if (errors.length > 0) {
        throw new Error(`${file}: the configuration of ${languageId} does not parse`);
    }
    const comments = configuration?.comments;
    const result = {};
    if (comments === undefined || comments === null || typeof comments !== 'object' || Array.isArray(comments)) {
        return result;
    }
    const line = comments.lineComment;
    if (isToken(line)) {
        result.line = line;
        result.lineNoIndent = false;
    } else if (line && typeof line === 'object' && isToken(line.comment)) {
        result.line = line.comment;
        result.lineNoIndent = line.noIndent === true;
    }
    const block = comments.blockComment;
    if (Array.isArray(block) && block.length === 2 && isToken(block[0]) && isToken(block[1])) {
        result.block = [block[0], block[1]];
    }
    return result;
}

const order = [];
const tokens = new Map();
for (const { folder, language } of builtinLanguageContributions(vscodeDir)) {
    if (!order.includes(language.id)) {
        order.push(language.id);
    }
    if (typeof language.configuration !== 'string') {
        continue;
    }
    const read = readComments(path.join(folder, language.configuration), language.id);
    const merged = { ...tokens.get(language.id) };
    if (read.line !== undefined) {
        merged.line = read.line;
        merged.lineNoIndent = read.lineNoIndent;
    }
    if (read.block !== undefined) {
        merged.block = read.block;
    }
    tokens.set(language.id, merged);
}

const rows = [];
for (const id of order) {
    const found = tokens.get(id);
    if (!found || (found.line === undefined && found.block === undefined)) {
        continue;
    }
    rows.push(
        `    {${quote(id)}, ${quote(found.line ?? '')}, ${found.lineNoIndent === true}, ` +
            `${quote(found.block?.[0] ?? '')}, ${quote(found.block?.[1] ?? '')}},`,
    );
}

const generated = [
    '// Generated by scripts/generate-language-comments.mjs; do not edit.',
    `// The comment tokens of the languages of VS Code ${version}, from the \`comments\` of the language`,
    '// configurations of its built-in extensions (MIT, Copyright (c) Microsoft Corporation).',
    '#pragma once',
    '',
    '#include <string_view>',
    '',
    'namespace anvil::core {',
    '',
    '// An empty `line` or `block_open` means the language has no such token.',
    'struct LanguageCommentsRow {',
    '    std::string_view id;',
    '    std::string_view line;',
    '    bool line_no_indent;',
    '    std::string_view block_open;',
    '    std::string_view block_close;',
    '};',
    '',
    'inline constexpr LanguageCommentsRow language_comments_table[] = {',
    ...rows,
    '};',
    '',
    '} // namespace anvil::core',
    '',
].join('\n');

if (process.argv.includes('--check')) {
    const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
    if (current !== generated) {
        console.error(`${path.relative(root, output)} is out of date; run node scripts/generate-language-comments.mjs`);
        process.exit(1);
    }
    console.log(`language comments table up to date (${rows.length} languages, VS Code ${version})`);
} else {
    fs.writeFileSync(output, generated);
    console.log(`wrote ${path.relative(root, output)} (${rows.length} languages, VS Code ${version})`);
}
