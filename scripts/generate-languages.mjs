// Generates src/core/include/anvil/core/language_table.hpp: the languages of VS Code (`plaintext`
// and the `contributes.languages` of its built-in extensions) with the rules that give a file its
// language, in the order VS Code registers them, read from the pinned checkout.
//   node scripts/generate-languages.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readBuiltinLanguages, vscodeVersion } from './builtin-languages.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const vscodeDir = path.join(root, '.deps', 'vscode');
const output = path.join(root, 'src/core/include/anvil/core/language_table.hpp');

const version = vscodeVersion(vscodeDir);
const languages = await readBuiltinLanguages(vscodeDir);

function quote(text) {
    if (/[\u0000-\u001f\u007f]/.test(text)) {
        throw new Error(`a control character in ${JSON.stringify(text)}`);
    }
    return `"${text.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
}

const lines = [];
const rows = [];
languages.forEach((language, index) => {
    const array = (field, values) => {
        if (!values || values.length === 0) {
            return '{}';
        }
        const name = `language_${index}_${field}`;
        lines.push(`inline constexpr std::string_view ${name}[] = {${values.map(quote).join(', ')}};`);
        return name;
    };
    const aliases =
        language.aliases === undefined
            ? 'std::nullopt'
            : language.aliases.length === 0
              ? 'std::span<const std::string_view>{}'
              : array('aliases', language.aliases);
    rows.push(
        `    {${quote(language.id)}, ${aliases}, ` +
            `${array('extensions', language.extensions)}, ${array('filenames', language.filenames)}, ` +
            `${array('filename_patterns', language.filenamePatterns)}, ${quote(language.firstLine ?? '')}, ` +
            `${array('mime_types', language.mimetypes)}},`,
    );
});

const generated = [
    '// Generated by scripts/generate-languages.mjs; do not edit.',
    `// The languages of VS Code ${version} in the order it registers them, from \`plaintext\` and the`,
    '// `contributes.languages` of its built-in extensions (MIT, Copyright (c) Microsoft Corporation).',
    '#pragma once',
    '',
    '#include <optional>',
    '#include <span>',
    '#include <string_view>',
    '',
    'namespace anvil::core {',
    '',
    'struct LanguageRow {',
    '    std::string_view id;',
    '    // Absent when the contribution has no `aliases`, which names the language by its id; empty when it',
    '    // has an empty list, which gives it no name.',
    '    std::optional<std::span<const std::string_view>> aliases;',
    '    std::span<const std::string_view> extensions;',
    '    std::span<const std::string_view> filenames;',
    '    std::span<const std::string_view> filename_patterns;',
    '    std::string_view first_line;',
    '    std::span<const std::string_view> mime_types;',
    '};',
    '',
    ...lines,
    '',
    'inline constexpr LanguageRow language_table[] = {',
    ...rows,
    '};',
    '',
    '} // namespace anvil::core',
    '',
].join('\n');

if (process.argv.includes('--check')) {
    const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
    if (current !== generated) {
        console.error(`${path.relative(root, output)} is out of date; run node scripts/generate-languages.mjs`);
        process.exit(1);
    }
    console.log(`language table up to date (${languages.length} languages, VS Code ${version})`);
} else {
    fs.writeFileSync(output, generated);
    console.log(`language table: ${languages.length} languages (VS Code ${version})`);
}
