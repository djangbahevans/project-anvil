// Generates src/core/include/anvil/core/key_table.hpp: the keys of VS Code's `KeyCode`, with the spellings that key
// bindings use for them, read from the pinned checkout. One table serves the parser, the formatters
// and, later, the translation of Qt key events.
//   node scripts/generate-key-table.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const vscodeDir = path.join(root, '.deps', 'vscode');
const output = path.join(root, 'src/core/include/anvil/core/key_table.hpp');

const { KeyCode, KeyCodeUtils } = await import(path.join(vscodeDir, 'out/vs/base/common/keyCodes.js'));
const version = JSON.parse(fs.readFileSync(path.join(vscodeDir, 'package.json'), 'utf8')).version;

// Not keys of a keyboard: placeholders of the enumeration, and the state of an input method.
const skipped = new Set(['DependsOnKbLayout', 'Unknown', 'KEY_IN_COMPOSITION', 'MAX_VALUE']);

const snake = (name) =>
    /^[A-Z0-9_]+$/.test(name) ? name.toLowerCase() : name.replace(/([a-z])([A-Z])/g, '$1_$2').toLowerCase();

// Names that C++ does not allow for an enumerator.
const reserved = new Set(['delete']);

const keys = Object.keys(KeyCode)
    .filter((name) => Number.isNaN(Number(name)) && !skipped.has(name))
    .map((name) => ({ name, id: reserved.has(snake(name)) ? `${snake(name)}_key` : snake(name), code: KeyCode[name] }))
    .sort((a, b) => a.code - b.code);

const quote = (text) => `"${text.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
const rows = keys.map(({ id, code }) => {
    const label = KeyCodeUtils.toString(code);
    const setting = KeyCodeUtils.toUserSettingsUS(code).toLowerCase();
    const general = KeyCodeUtils.toUserSettingsGeneral(code).toLowerCase();
    return { id, label, setting, alias: general === setting ? '' : general };
});

const ids = new Set(rows.map((row) => row.id));
if (ids.size !== rows.length) {
    throw new Error('two keys have the same identifier');
}
const spellings = new Map();
for (const row of rows) {
    for (const spelling of [row.setting, row.alias].filter((s) => s !== '')) {
        if (spellings.has(spelling)) {
            throw new Error(`the spelling ${spelling} names two keys`);
        }
        spellings.set(spelling, row.id);
    }
}

const generated = [
    '// Generated by scripts/generate-key-table.mjs; do not edit.',
    `// The keys of VS Code ${version} (\`KeyCode\`), in its order, with the spellings key bindings use.`,
    '#pragma once',
    '',
    '#include <cstdint>',
    '#include <string_view>',
    '',
    'namespace anvil::core {',
    '',
    'enum class Key : std::uint8_t {',
    ...rows.map((row) => `    ${row.id},`),
    '};',
    '',
    'struct KeyInfo {',
    '    Key key;',
    '    // How the key is shown in the interface.',
    '    std::string_view label;',
    '    // The lowercase name in a key binding, as VS Code writes it for a US keyboard.',
    '    std::string_view setting;',
    '    // Another name that a key binding can use for the key, or empty.',
    '    std::string_view alias;',
    '};',
    '',
    'inline constexpr KeyInfo key_table[] = {',
    ...rows.map((row) => `    {Key::${row.id}, ${quote(row.label)}, ${quote(row.setting)}, ${quote(row.alias)}},`),
    '};',
    '',
    '} // namespace anvil::core',
    '',
].join('\n');

if (process.argv.includes('--check')) {
    const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
    if (current !== generated) {
        console.error(`${path.relative(root, output)} is out of date; run node scripts/generate-key-table.mjs`);
        process.exit(1);
    }
    console.log(`key table up to date (${rows.length} keys, VS Code ${version})`);
} else {
    fs.writeFileSync(output, generated);
    console.log(`key table: ${rows.length} keys (VS Code ${version})`);
}
