// Writes src/core/grapheme_table.hpp, the grapheme cluster break classes of code points, from the
// data that VS Code splits grapheme clusters with (src/vs/base/common/strings.ts).
//   node scripts/generate-grapheme-table.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const vscodeDir = path.join(root, '.deps', 'vscode');
const output = path.join(root, 'src/core/grapheme_table.hpp');

const source = fs.readFileSync(path.join(vscodeDir, 'src/vs/base/common/strings.ts'), 'utf8');
const version = JSON.parse(fs.readFileSync(path.join(vscodeDir, 'package.json'), 'utf8')).version;

const classes = /export const enum GraphemeBreakType \{([^}]*)\}/.exec(source)[1]
    .split(',')
    .map((entry) => entry.trim())
    .filter(Boolean)
    .map((entry, index) => {
        const [name, value] = entry.split('=').map((part) => part.trim());
        if (Number(value) !== index) {
            throw new Error(`unexpected value of ${name}`);
        }
        return name.toLowerCase();
    });

// The data is a search tree of [first, last, class] triples; the first triple is unused.
const data = JSON.parse(/function getGraphemeBreakRawData\(\)[^]*?JSON\.parse\('([^']*)'\)/.exec(source)[1]);
const ranges = [];
for (let i = 3; i < data.length; i += 3) {
    ranges.push([data[i], data[i + 1], data[i + 2]]);
}
ranges.sort((a, b) => a[0] - b[0]);
for (let i = 1; i < ranges.length; i++) {
    if (ranges[i][0] <= ranges[i - 1][1]) {
        throw new Error(`ranges overlap at ${ranges[i][0]}`);
    }
}

const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
const names = classes.map((name) => (name === 'extended_pictographic' ? 'pictographic' : name));
const text = `// Generated by scripts/generate-grapheme-table.mjs; do not edit.
// The grapheme cluster break classes of VS Code ${version} (MIT, Copyright (c) Microsoft Corporation).
#pragma once

#include <cstdint>

namespace anvil::core {

enum class GraphemeClass : std::uint8_t {
${names.map((name) => `    ${name},`).join('\n')}
};

struct GraphemeRange {
    char32_t first;
    char32_t last;
    GraphemeClass type;
};

// Sorted, and disjoint; a code point in no range is \`other\`.
inline constexpr GraphemeRange grapheme_ranges[] = {
${ranges.map(([first, last, type]) => `    {${hex(first)}, ${hex(last)}, GraphemeClass::${names[type]}},`).join('\n')}
};

} // namespace anvil::core
`;

if (process.argv.includes('--check')) {
    if (fs.readFileSync(output, 'utf8') !== text) {
        console.error(`${output} is out of date`);
        process.exit(1);
    }
} else {
    fs.writeFileSync(output, text);
}
