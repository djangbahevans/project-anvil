// Refreshes what the editor ships of VS Code's Codicons from the copy in the pinned checkout
// (@vscode/codicons): the font, copied byte for byte, its license text, and the table of icon names
// and code points in src/ui/codicon_table.hpp.
//   node scripts/generate-codicons.mjs [--check]
// --check changes nothing and fails when any of the three differs from the checkout.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageDir = path.join(root, '.deps', 'vscode', 'node_modules', '@vscode', 'codicons');
const fontOutput = path.join(root, 'resources', 'codicons', 'codicon.ttf');
const licenseOutput = path.join(root, 'resources', 'codicons', 'LICENSE-codicons.txt');
const tableOutput = path.join(root, 'src', 'ui', 'codicon_table.hpp');
const check = process.argv.includes('--check');

const version = JSON.parse(fs.readFileSync(path.join(packageDir, 'package.json'), 'utf8')).version;
const lines = fs.readFileSync(path.join(packageDir, 'dist', 'codicon.csv'), 'utf8').split(/\r?\n/).filter((line) => line.length > 0);
if (lines[0] !== 'short_name,character,unicode') {
    throw new Error(`unexpected header of codicon.csv: ${lines[0]}`);
}

const entries = lines.slice(1).map((line) => {
    const match = /^([A-Za-z0-9-]+),(.),([0-9A-F]{4})$/u.exec(line);
    if (!match) {
        throw new Error(`unexpected line of codicon.csv: ${line}`);
    }
    const [, name, character, hex] = match;
    if (character.codePointAt(0) !== parseInt(hex, 16)) {
        throw new Error(`${name}: the character and the code point differ`);
    }
    return { name, hex };
});
entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
if (new Set(entries.map((entry) => entry.name)).size !== entries.length) {
    throw new Error('duplicate icon names in codicon.csv');
}

const table = [
    '// Generated by scripts/generate-codicons.mjs; do not edit.',
    `// The icons of @vscode/codicons ${version}, ordered by name, with their code points in the font.`,
    '#pragma once',
    '',
    '#include "anvil/ui/codicons.hpp"',
    '',
    'namespace anvil::ui {',
    '',
    'inline constexpr CodiconEntry codicon_table_data[] = {',
    ...entries.map((entry) => `    {"${entry.name}", 0x${entry.hex}},`),
    '};',
    '',
    '} // namespace anvil::ui',
    '',
].join('\n');

const wanted = [
    [fontOutput, fs.readFileSync(path.join(packageDir, 'dist', 'codicon.ttf'))],
    [licenseOutput, fs.readFileSync(path.join(packageDir, 'LICENSE'))],
    [tableOutput, Buffer.from(table)],
];

const differences = [];
for (const [target, content] of wanted) {
    const current = fs.existsSync(target) ? fs.readFileSync(target) : null;
    if (current === null || !current.equals(content)) {
        differences.push(path.relative(root, target));
        if (!check) {
            fs.mkdirSync(path.dirname(target), { recursive: true });
            fs.writeFileSync(target, content);
        }
    }
}

if (check) {
    if (differences.length > 0) {
        console.error(`${differences.join(', ')} out of date; run node scripts/generate-codicons.mjs`);
        process.exit(1);
    }
    console.log(`codicons up to date (${entries.length} icons, @vscode/codicons ${version})`);
} else {
    console.log(`codicons: ${entries.length} icons, ${differences.length} files written (@vscode/codicons ${version})`);
}
