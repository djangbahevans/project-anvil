// Generates src/exthost/include/anvil/exthost/proxy_ids.hpp from the proxy identifiers declared in
// the pinned VS Code checkout. Identifiers are numbered by creation order, so the table must be
// regenerated whenever the pinned release changes.
//   node scripts/generate-proxy-ids.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const vscodeDir = path.join(root, '.deps', 'vscode');
const output = path.join(root, 'src/exthost/include/anvil/exthost/proxy_ids.hpp');

const protocolSource = fs.readFileSync(path.join(vscodeDir, 'src/vs/workbench/api/common/extHost.protocol.ts'), 'utf8');
const version = JSON.parse(fs.readFileSync(path.join(vscodeDir, 'package.json'), 'utf8')).version;
const names = [...protocolSource.matchAll(/createProxyIdentifier<[^>]*>\('([A-Za-z0-9_]+)'\)/g)].map((m) => m[1]);

if (new Set(names).size !== names.length) {
    throw new Error('duplicate proxy identifier names in the protocol source');
}
if (names.length > 255) {
    throw new Error('proxy identifiers no longer fit the one-byte rpcId field');
}

const lines = [
    '// Generated by scripts/generate-proxy-ids.mjs; do not edit.',
    `// Proxy identifiers of VS Code ${version}, numbered by creation order in extHost.protocol.ts.`,
    '#pragma once',
    '',
    '#include <cstdint>',
    '#include <string_view>',
    '',
    'namespace anvil::exthost {',
    '',
    'enum class ProxyId : std::uint8_t {',
    ...names.map((name, i) => `    ${name} = ${i + 1},`),
    '};',
    '',
    `inline constexpr std::uint8_t proxy_id_count = ${names.length};`,
    '',
    'inline constexpr std::string_view proxy_names[] = {',
    ...names.map((name) => `    "${name}",`),
    '};',
    '',
    '// Name of the proxy identifier, or an empty view for an id outside the table.',
    'constexpr std::string_view proxy_name(std::uint8_t id) {',
    '    return id >= 1 && id <= proxy_id_count ? proxy_names[id - 1] : std::string_view{};',
    '}',
    '',
    '} // namespace anvil::exthost',
    '',
];
const generated = lines.join('\n');

if (process.argv.includes('--check')) {
    const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
    if (current !== generated) {
        console.error(`${path.relative(root, output)} is out of date; run scripts/generate-proxy-ids.mjs`);
        process.exit(1);
    }
    console.log(`proxy ids up to date (${names.length} identifiers, VS Code ${version})`);
} else {
    fs.writeFileSync(output, generated);
    console.log(`wrote ${names.length} identifiers for VS Code ${version}`);
}
